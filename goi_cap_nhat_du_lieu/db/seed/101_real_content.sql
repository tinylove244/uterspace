DELETE r FROM reports r JOIN comments c ON r.target_type = 'COMMENT' AND r.target_id = c.comment_id
  JOIN tmp_old_posts o ON c.post_id = o.post_id;
DELETE n FROM notifications n JOIN tmp_old_posts o
  ON n.type IN ('LIKE', 'COMMENT', 'SHARE', 'GROUP_POST')
 AND CAST(SUBSTRING(REGEXP_SUBSTR(n.target_url, 'post-[0-9]+$'), 6) AS UNSIGNED) = o.post_id;
-- comments, likes, saved_posts xóa theo ON DELETE CASCADE
